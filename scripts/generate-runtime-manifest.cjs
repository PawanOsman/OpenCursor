// Generate only from the committed lockfile; no live semver resolution.
const fs = require('node:fs');
const yaml = require('js-yaml');
const lock = yaml.load(fs.readFileSync('pnpm-lock.yaml', 'utf8'));
const names = ['@huggingface/transformers', '@huggingface/hub', 'onnxruntime-node', 'sharp', 'pdf-parse', '@lydell/node-pty', 'playwright-core'];
const roots = Object.fromEntries(names.map(name => [name, `${name}@${lock.importers['.'].dependencies[name].version}`]));
const drop = { '@huggingface/transformers': ['onnxruntime-web'], 'onnxruntime-node': ['adm-zip', 'global-agent'] };
const packages = {};
const queue = Object.values(roots);
while (queue.length) {
  const id = queue.shift(); if (packages[id]) continue;
  const snapshot = lock.snapshots[id]; const meta = lock.packages[id];
  if (!snapshot || !meta?.resolution?.integrity) throw new Error(`Missing pinned package ${id}`);
  const split = id.lastIndexOf('@'); const name = id.slice(0, split); const version = id.slice(split + 1);
  if (!/^\d+\.\d+\.\d+(?:-[\w.-]+)?$/.test(version)) throw new Error(`Unsupported snapshot ${id}`);
  const deps = field => Object.fromEntries(Object.entries(snapshot[field] || {}).filter(([n]) => !drop[name]?.includes(n)).map(([n, v]) => [n, `${n}@${v}`]));
  const dependencies = deps('dependencies'), optionalDependencies = deps('optionalDependencies');
  // transformers 4.2.0's Node distribution imports Tensor directly from this
  // transitive package. Pin the same version as its native ONNX runtime.
  if (name === '@huggingface/transformers') {
    const ort = lock.snapshots[dependencies['onnxruntime-node']];
    dependencies['onnxruntime-common'] = `onnxruntime-common@${ort.dependencies['onnxruntime-common']}`;
  }
  packages[id] = {
    name, version, integrity: meta.resolution.integrity,
    tarball: `https://registry.npmjs.org/${name}/-/${name.split('/').pop()}-${version}.tgz`,
    ...(meta.os ? { os: meta.os } : {}), ...(meta.cpu ? { cpu: meta.cpu } : {}), ...(meta.libc ? { libc: meta.libc } : {}),
    dependencies, optionalDependencies,
  };
  queue.push(...Object.values(dependencies), ...Object.values(optionalDependencies));
}
const manifest = { version: 1, roots, packages: Object.fromEntries(Object.entries(packages).sort(([a], [b]) => a.localeCompare(b))) };
const licenseHeader = `/*
 * Copyright (c) 2026 Pawan Osman <https://github.com/PawanOsman>
 *
 * This file is part of OpenCursor — AI coding agent chat inside VS Code.
 * https://github.com/PawanOsman/OpenCursor
 *
 * Licensed under the MIT License. See LICENSE file in the project root.
 */

`;
const output = licenseHeader + '// Generated by scripts/generate-runtime-manifest.cjs from pnpm-lock.yaml.\nexport const runtimeManifest = ' + JSON.stringify(manifest, null, 2) + ' as const;\n';
const file = 'src/runtimeManifest.ts';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(file, 'utf8') !== output) throw new Error('Runtime manifest is stale; run pnpm runtime:manifest');
} else fs.writeFileSync(file, output);
